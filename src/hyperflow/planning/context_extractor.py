"""
Context Extraction for HyperFlow AI.

Implements the backward expansion algorithm from the paper:
"Given a user request, HyperAgent first extracts a task-relevant
Tool Context Graph from the full TSH."

Key components:
1. Task Interpretation - LLM generates structured task description
2. Seed Hyperedge Anchoring - Semantic retrieval of initial tools
3. Seed Node Anchoring - Schema-level anchoring
4. Bounded Backward Search - Expansion along dependency edges
5. Context Graph Construction - Induced subgraph

This is a critical component that reduces the global tool space
while preserving schema-level dependencies.

Production considerations:
- Efficient caching of semantic similarities
- Configurable hop count and beam width
- Graceful degradation when embeddings fail
- Support for incremental context updates
"""

from dataclasses import dataclass, field
import logging
from typing import Dict, List, Optional, Set, Tuple
from uuid import UUID

from hyperflow.core.models import Node, NodeType, ToolSchemaHypergraph
from hyperflow.utils.embeddings import EmbeddingManager, SimilarityScorer


logger = logging.getLogger(__name__)

@dataclass
class ContextExtractionConfig:
    """Configuration for context extraction."""

    # number of seed hyperedges to retrive
    seed_hyperedges_k: int = 10

    # number of seed nodes to retrive per side 
    seed_nodes_k: int = 20

    # similarity thresholds
    hyperedge_threshold: float = 0.5
    node_threshold: float = 0.4

    #backward expansion
    max_hops: int = 2
    producers_per_node: int = 5

    # beam width for candidate selection
    beam_width: int = 100

    # maximum context graph size
    max_context_size: int = 100

@dataclass
class TaskInterpretation:
    """
    Structured interpretation of a user request.
    
    Generated by LLM to guide context extraction.
    """
    operations: str = ""
    schemas: str = ""
    entities: List[str] = field(default_factory=list)
    constraint: List[str] = field(default_factory=list)
    desired_outcomes: List[str] = field(default_factory=list)
    raw_text: str = ""

    def get_operation_text(self) -> str:
        # get operation-level description
        return self.operations

    def get_schema_text(self) -> str:
        # get schema level description
        return self.schemas

class ContextExtractor:
    """
    Extracts task-relevant context graphs from the hypergraph.
    
    Implements the bounded backward search described in the paper.
    
    Process:
    1. Annotate seed hyperedges based on operation similarity
    2. Annotate seed nodes based on schema similarity
    3. Expand backward from seed nodes along dependencies
    4. Build the induced Tool Context Graph
    
    The context graph provides a compact planning space that
    preserves schema-level dependencies.
    """

    def __init__(
            self,
            hypergraph: ToolSchemaHypergraph,
            config: Optional[ContextExtractionConfig] = None,
            embedder: Optional[EmbeddingManager] = None
    ):
        """
        Initialize the context extractor.
        
        Args:
            hypergraph: The full Tool-Schema Hypergraph
            config: Configuration options
            embedder: Embedding manager for semantic similarity
        """
        self.hypergraph = hypergraph
        self.config = config or ContextExtractionConfig()

        # intialize embedder if not provided
        if embedder is None:
            embedder = EmbeddingManager()
        self.embedder = embedder
        self.scorer = SimilarityScorer(embedder)

        # precompute tool descritions for similarity
        self._tool_descriptions = self._precompute_descriptions()

        #cache for similarity scores
        self._similarity_cache: Dict[str, float] = {}

    def _precompute_descriptions(self) -> Dict[UUID, str]:
        # precompute tool descriptions for efficient retrival
        descriptions = {}
        for edge_id, edge in self.hypergraph.hyperedges.items():
            # combine name and description
            desc = f"{edge.name}: {edge.description}"
            descriptions[edge_id] = desc
        return descriptions

    def extract_context(
        self,
        task: str,
        task_interpretation: Optional[TaskInterpretation] = None
    ) -> ToolSchemaHypergraph:
        """
        Extract a task-relevant context graph.
        
        Args:
            task: User request text
            task_interpretation: Optional pre-computed interpretation
            
        Returns:
            Tool Context Graph (subhypergraph)
        """
        logger.info(f"extracting context for task: {task[:100]}...")

        # step 1: get task interperetation
        if task_interpretation is None:
            task_interpretation = self._interprete_task(task)

        # step 2: anchor seed hyperedges
        seed_edges = self._anchor_seed_hyperedges(task_interpretation)
        logger.info(f"anchored {len(seed_edges)} seed hyperedges")

        # step 3: anchor seed nodes
        seed_nodes = self._anchor_seed_nodes(task_interpretation)
        logger.info(f"anchored{len(seed_nodes)} seed nodes")

        # step 4: expand seed nodes with associated tools
        associated_edges = self._add_associated_tools(seed_nodes)
        seed_edges.update(associated_edges)

        # step 5: backward expansion
        explanded_edges = self._backward_expansion(seed_nodes, seed_edges)
        seed_edges.update(explanded_edges)

        # step 6: build the context graph
        context_graph = self.hypergraph.get_subgraph(seed_edges)

        # step 7: validate and ensure it's not empty
        if len(context_graph.hyperedges) == 0:
            logger.warning("empty context graph, using fallback")
            context_graph = self._fallback_context()

        logger.info(f"context graph: {len(context_graph.hyperedges)} tpp;s, "
                    f"{len(context_graph.nodes)} nodes,"
                    f"{len(context_graph.dependencies)} dependencies")

        return context_graph
    
    def _interpret_task(self, task: str) -> TaskInterpretation:
        """
        Generate a structured interpretation of the task.
        
        In production, this would call an LLM. For now, we use a simple
        heuristic-based approach.
        """
        # For MVP, use a simple extraction
        # In production, this would be an LLM call with prompt engineering

        # replace with LLM based interpretation
        # for now we use task as both operation and schema text
        return TaskInterpretation(
            operations=task,
            schemas=task,
            entities=[],
            constraints=[],
            desired_outcomes=[],
            raw_text=task
        )

    def _anchor_seed_hyperedges(
            self,
            interpretation: TaskInterpretation,
    ) -> Set[UUID]:
        """
        Anchor seed hyperedges based on operation-level similarity.
        
        Selects top-K hyperedges with operation similarity above threshold.
        """
        operation_text = interpretation.get_operation_text()

        if not operation_text:
            return set()

        #compute similarities for all tools
        similarities = []
        for edge_id, desc in self._tool_descriptions.items():
            #use chached similairty if available
            cache_key = f"op_{edge_id}_{operation_text}"
            if cache_key in self._similarity_cache:
                sim = self._similarity_cache[cache_key]
            else:
                sim = self.scorer.score(desc, operation_text)
                self._similarity_cache[cache_key] = sim

            if sim >= self.config.hyperedge_threshold:
                similarities.append((edge_id, sim))

        # sort by similarity and take top-k
        similarities.sort(key=lambda x: x[1], reverse=True)
        top_edges = similarities[:self.config.seed_hyperedges_k]

        return {edge_id for edge_id, _ in top_edges}

    def _anchor_seed_nodes(self, interpretation: TaskInterpretation) -> Set[UUID]:
        """
        Anchor seed nodes based on schema-level similarity.
        
        Selects top-K input and output nodes with similarity above threshold.
        """
        schema_text = interpretation.get_schema_text()

        if not schema_text:
            return set()

        # separate input and output nodes
        input_nodes = [
            n for n in self.hypergraph.nodes.values()
            if n.node_type == NodeType.INPUT_SCHEMA
        ]
        output_nodes = [
            n for n in self.hypergraph.nodes.values()
            if n.node_type == NodeType.OUTPUT_SCHEMA
        ]

        seed_nodes = set()

        # score input nodes
        input_scores = self._score_nodes(input_nodes, schema_text)
        for node_id, score in input_scores[:self.config.seed_nodes_k]:
            if score >= self.config.node_threshold:
                seed_nodes.add(node_id)

        # score output nodes
        output_scores = self._score_nodes(output_nodes, schema_text)
        for node_id, score in output_scores[:self.config.seed_nodes_k]:
            if score >= self.config.node_threshold:
                seed_nodes.add(node_id)

        return seed_nodes

    def _score_nodes(self, nodes: List[Node], query: str) -> List[Tuple[UUID, float]]:
        # score nodes by semantic similarity to query
        scores = []

        for node in nodes:
            #create description from node name and description
            node_text = f"{node.name}: {node.description}"

            # use cached similarity if available 
            cache_key = f"node{node.id}_{query}"
            if cache_key in self._similarity_cache:
                sim = self._similarity_cache[cache_key]
            else:
                sim = self.scorer.score(node_text, query)
                self._similarity_cache[cache_key] = sim

            scores.append((node.id, sim))

        scores.sort(key=lambda x: x[1], reverse=True)
        return scores

    def _add_associated_tools(self, seed_nodes: Set[UUID]) -> Set[UUID]:
        """
        Add tools directly associated with seed nodes.
        
        For output nodes: add producer tools
        For input nodes: add consumer tools
        """
        associated_edges = set()

        for node_id in seed_nodes:
            node = self.hypergraph.nodes.get(node_id)
            if not node:
                continue

            if node.node_type == NodeType.OUTPUT_SCHEMA:
                # find producer tools
                for edge_id, edge in self.hypergraph.hyperedges.items():
                    if node_id in edge.output_nodes:
                        associated_edges.add(edge_id)

            elif node.node_type == NodeType.INPUT_SCHEMA:
                # find consumer tools
                for edge_id, edge in self.hypergraph.hyperedges.items():
                    if node_id in edge.input_nodes:
                        associated_edges.add(edge_id)

            elif node.node_type == NodeType.EFFECT:
                # find effect producers
                for edge_id, edge in self.hypergraph.hyperedges.items():
                    if node_id in edge.output_nodes:
                        associated_edges.add(edge_id)

        return associated_edges

    def _backward_expansion(self, seed_nodes: Set[UUID], seed_edges: set[UUID]) -> Set[UUID]:
        """
        Perform bounded backward expansion.
        
        Starting from seed nodes, follow dependency links backwards
        to find prerequisite tools.
        """
        expanded_edges = set()

        # initialize frontier with input nodes from seed edges
        frontier = set(seed_nodes)
        for edge_id in seed_edges:
            edge = self.hypergraph.hyperedges.get(edge_id)
            if edge: 
                frontier.update(edge.input_nodes)

        # backward expansion for each hop
        for hop in range(self.config.max_hops):
            logger.debug(f" backward expansion hop {hop + 1}: frontier size {len(frontier)}")


            new_frontier = set()
            producers_found = False

            for node_id in frontier:
                # find producers for this input node
                producers = self._find_producers(node_id)

                # add top-k producers
                for edge_id, weight in producers[:self.config.producers_per_node]:
                    expanded_edges.add(edge_id)
                    producers_found = True

                    # add producers input nodes to next frontier 
                    edge = self.hypergraph.hyperedges.get(edge_id)
                    if edge: 
                        new_frontier.update(edge.input_nodes)

            frontier = new_frontier

            # stop if no new producers found
            if not producers_found:
                break

        return expanded_edges

    def _find_producers(self, node_id: UUID) -> List[Tuple[UUID, float]]:
        """
        Find producer tools for a node.
        
        Uses the support matrix for efficient lookup.
        """
        node = self.hypergraph.nodes.get(node_id)
        if not node:
            return []

        # check if this is an input node
        if node.node_type != NodeType.INPUT_SCHEMA:
            return []

        # use support matrix if available
        if hasattr(self.hypergraph, '_support_matrix'):
            matrix = self.hypergraph._support_matrix
            # this assumers the matrix has been built and use the dependency based method

        # fallback: find producers through dependencies
        producers = []
        for dep in self.hypergraph.dependencies.values():
            if dep.target_node == node_id:
                # find which hyperedge produces the source
                for edge_id, edge in self.hypergraph.hyperedges.items():
                    if dep.source_node in edge.output_nodes:
                        producers.append((edge_id, dep.weight))
                        break

        # sort by weight
        producers.sort(key=lambda x: x[1], reverse=True)
        return producers

    


        
        
