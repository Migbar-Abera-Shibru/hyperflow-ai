"""
Context Extraction for HyperFlow AI.

Implements the backward expansion algorithm from the paper:
"Given a user request, HyperAgent first extracts a task-relevant
Tool Context Graph from the full TSH."

Key components:
1. Task Interpretation - LLM generates structured task description
2. Seed Hyperedge Anchoring - Semantic retrieval of initial tools
3. Seed Node Anchoring - Schema-level anchoring
4. Bounded Backward Search - Expansion along dependency edges
5. Context Graph Construction - Induced subgraph

This is a critical component that reduces the global tool space
while preserving schema-level dependencies.

Production considerations:
- Efficient caching of semantic similarities
- Configurable hop count and beam width
- Graceful degradation when embeddings fail
- Support for incremental context updates
"""

from dataclasses import dataclass, field
import logging
from typing import Dict, List, Optional
from uuid import UUID

from hyperflow.core.models import ToolSchemaHypergraph
from hyperflow.utils.embeddings import EmbeddingManager, SimilarityScorer


logger = logging.getLogger(__name__)

@dataclass
class ContextExtractionConfig:
    """Configuration for context extraction."""

    # number of seed hyperedges to retrive
    seed_hyperedges_k: int = 10

    # number of seed nodes to retrive per side 
    seed_nodes_k: int = 20

    # similarity thresholds
    hyperedge_threshold: float = 0.5
    node_threshold: float = 0.4

    #backward expansion
    max_hops: int = 2
    producers_per_node: int = 5

    # beam width for candidate selection
    beam_width: int = 100

    # maximum context graph size
    max_context_size: int = 100

@dataclass
class TastInterpretation:
    """
    Structured interpretation of a user request.
    
    Generated by LLM to guide context extraction.
    """
    operations: str = ""
    schemas: str = ""
    entities: List[str] = field(default_factory=list)
    constraint: List[str] = field(default_factory=list)
    desired_outcomes: List[str] = field(default_factory=list)
    raw_text: str = ""

    def get_operation_text(self) -> str:
        # get operation-level description
        return self.operations

    def get_schema_text(self) -> str:
        # get schema level description
        return self.schemas

class ContextExtractor:
    """
    Extracts task-relevant context graphs from the hypergraph.
    
    Implements the bounded backward search described in the paper.
    
    Process:
    1. Annotate seed hyperedges based on operation similarity
    2. Annotate seed nodes based on schema similarity
    3. Expand backward from seed nodes along dependencies
    4. Build the induced Tool Context Graph
    
    The context graph provides a compact planning space that
    preserves schema-level dependencies.
    """

    def __init__(
            self,
            hypergraph: ToolSchemaHypergraph,
            config: Optional[ContextExtractionConfig] = None,
            embedder: Optional[EmbeddingManager] = None
    ):
        """
        Initialize the context extractor.
        
        Args:
            hypergraph: The full Tool-Schema Hypergraph
            config: Configuration options
            embedder: Embedding manager for semantic similarity
        """
        self.hypergraph = hypergraph
        self.config = config or ContextExtractionConfig()

        # intialize embedder if not provided
        if embedder is None:
            embedder = EmbeddingManager()
        self.embedder = embedder
        self.scorer = SimilarityScorer(embedder)

        # precompute tool descritions for similarity
        self._tool_descriptions = self._precompute_descriptions()

        #cache for similarity scores
        self._similarity_cache: Dict[str, float] = {}

    def _precompute_descriptions(self) -> Dict[UUID, str]:
        # precompute tool descriptions for efficient retrival
        descriptions = {}
        for edge_id, edge in self.hypergraph.hyperedges.items():
            # combine name and description
            desc = f"{edge.name}: {edge.description}"
            descriptions[edge_id] = desc
        return descriptions
        
